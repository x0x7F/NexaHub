                    Conversation.ofId(
                        id = conversationId,
                        assistantId = assistant.id,
                        newConversation = true
                    ).updateCurrentMessages(assistant.presetMessages)
                }
            }
            settingsStore.updateAssistant(session.state.value.assistantId)
        }
    }

